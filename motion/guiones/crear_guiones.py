"""Define los guiones con escenas de la serie y los escribe como guiones/<id>.json.
Uso: python3 guiones/crear_guiones.py

Cada beat: texto (lo que se dice), keys (palabras resaltadas), sfx ([efecto, palabra]) y escena
(momentos con elementos; ver src/serie/Bloques.tsx para los tipos de elemento).
"""

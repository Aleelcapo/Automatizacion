# ---------- atajos ----------
def tit(texto, en=None, **kw): return dict(t='titulo', texto=texto, en=en, **kw)
def txt(texto, en=None, **kw): return dict(t='texto', texto=texto, en=en, **kw)
def num(valor, en=None, **kw): return dict(t='numero', valor=valor, en=en, **kw)
def pil(texto, en=None, **kw): return dict(t='pildora', texto=texto, en=en, **kw)
def ico(nombre, en=None, **kw): return dict(t='icono', nombre=nombre, en=en, **kw)
def icos(items, en=None, **kw): return dict(t='iconos', items=items, en=en, **kw)
def tarj(items, en=None): return dict(t='tarjetas', items=items, en=en)
def barras(items, en=None, **kw): return dict(t='barras', items=items, en=en, **kw)
def pasos(items, en=None): return dict(t='pasos', items=items, en=en)
def lista(items, en=None): return dict(t='lista', items=items, en=en)
def sello(texto, en=None, **kw): return dict(t='sello', texto=texto, en=en, **kw)
def vs(a, b, en=None): return dict(t='vs', a=a, b=b, en=en)
def fila(items, en=None, **kw): return dict(t='fila', items=items, en=en, **kw)
def comenta(): return pil('Comenta abajo', fondo='oro', color='#2a1c00', size=48)


def beat(scene, text, el=None, momentos=None, keys=(), sfx=(), tinte=None, fondo=None):
    esc = {}
    if momentos:
        esc['momentos'] = [dict(en=m[0], el=m[1]) for m in momentos]
    else:
        esc['el'] = el or []
    if tinte: esc['tinte'] = tinte
    if fondo: esc['icono_fondo'] = fondo
    return dict(scene=scene, text=text, keys=list(keys), sfx=[list(s) for s in sfx], escena=esc)


